import { createRequire } from 'node:module'
import assert from 'node:assert/strict'

const { chromium } = createRequire(new URL('../web/package.json', import.meta.url))('playwright-core')
const [origin, admin] = process.argv.slice(2)
const token = process.env.RDNS_TEST_ADMIN_TOKEN
const browser = await chromium.launch({
  executablePath: process.env.RDNS_CHROME || '/bin/chromium',
  args: ['--no-sandbox'],
})
try {
  const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 390, height: 844 } })
  const page = await context.newPage()
  await page.goto(origin + '/')
  assert.equal(new URL(page.url()).pathname,'/portal')
  await page.getByRole('button',{name:'邮箱验证码登录'}).click()
  await page.getByLabel('登录邮箱').waitFor()
  await page.getByRole('button',{name:'发送邮箱验证码'}).waitFor()
  await page.getByRole('button',{name:'注册新账号'}).click()
  await page.getByRole('button',{name:'创建账户'}).waitFor()
  await page.getByRole('button',{name:'账号登录'}).click()
  await page.getByLabel('用户名').fill('alice')
  await page.getByLabel('密码').fill('test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await page.getByRole('heading', { name: 'alice 的 DNS' }).waitFor()
  await page.getByText('portal.test', { exact: true }).first().waitFor()
  await page.getByRole('button',{name:'扫码安装 iOS 描述文件',exact:true}).click()
  const qr = page.getByRole('img',{name:'用 iPhone 相机扫描以下载 iOS 描述文件'})
  await qr.waitFor()
  assert(await qr.evaluate(image=>image.complete && image.naturalWidth>=240))
  const link = await page.getByRole('link',{name:'打开扫码下载链接'}).getAttribute('href')
  const scanner = await browser.newContext({ignoreHTTPSErrors:true})
  try {
    const descriptor = await scanner.request.get(link)
    assert.equal(descriptor.status(),200)
    assert.equal(descriptor.headers()['content-type'],'application/x-apple-aspen-config')
    assert.equal((await scanner.request.get(link)).status(),404)
  } finally {
    await scanner.close()
  }
  const url = page.getByLabel('解析器 URL')
  const old = await url.inputValue()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '更换地址' }).click()
  await page.waitForFunction((previous) => document.querySelector('input[readonly]')?.value !== previous, old)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  const cookie = (await context.cookies()).find((c) => c.name === '__Host-rdns-portal')
  assert.ok(cookie?.httpOnly && cookie.secure)
  await page.getByRole('button', { name: '退出登录' }).click()
  await page.getByRole('heading', { name: '登录用户门户' }).waitFor()
  await page.goto(admin + '/')
  assert.equal(new URL(page.url()).pathname, '/portal')
  await page.getByRole('button',{name:'注册新账号'}).waitFor()
  await page.getByRole('button',{name:'邮箱验证码登录'}).click()
  await page.getByLabel('登录邮箱').waitFor()
  await page.goto(admin + '/admin')
  await page.evaluate((t) => sessionStorage.setItem('rdns-token', t), token)
  await page.reload()
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.getByRole('button', { name: '用户管理' }).click()
  await page.getByRole('button', { name: '管理员', exact:true }).click()
  await page.getByRole('heading',{name:'账号列表'}).waitFor()
  await page.getByRole('button', { name: '用户门户' }).click()
  await page.getByRole('heading', { name: '门户用户' }).waitFor()
  assert.deepEqual(await page.locator('aside nav button').evaluateAll(items=>items.slice(-2).map(item=>item.getAttribute('aria-label'))),['用户管理','高级设置'])
  await page.getByRole('button',{name:'新增用户',exact:true}).click()
  await page.getByLabel('用户名',{exact:true}).fill('managed-fixture')
  await page.getByLabel('初始密码',{exact:true}).fill('fixture-password')
  await page.getByRole('button',{name:'创建用户',exact:true}).click()
  await page.getByLabel('查找用户').fill('managed-fixture')
  const result = page.getByRole('row').filter({hasText:'managed-fixture'})
  await result.waitFor()
  await result.getByRole('button',{name:'编辑',exact:true}).click()
  await page.getByLabel('用户名',{exact:true}).fill('managed-fixture-updated')
  await page.getByLabel('新密码（可选）',{exact:true}).fill('updated-fixture-password')
  await page.getByRole('button',{name:'保存修改',exact:true}).click()
  await result.getByText('managed-fixture-updated',{exact:true}).waitFor()
  page.once('dialog',dialog=>dialog.accept())
  await result.getByRole('button',{name:'删除',exact:true}).click()
  await page.getByText('没有符合条件的用户',{exact:true}).waitFor()
  await page.getByLabel('查找用户').fill('')
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true)
  assert.equal(await page.locator('.portal-user-list .table-wrap').evaluate(el=>el.scrollWidth<=el.clientWidth+1),true)
  if (process.env.RDNS_LAYOUT_CAPTURE) await page.screenshot({path:process.env.RDNS_LAYOUT_CAPTURE+'/portal-admin-mobile.png'})
  await page.setViewportSize({width:1920,height:1000})
  if (process.env.RDNS_LAYOUT_CAPTURE) await page.screenshot({path:process.env.RDNS_LAYOUT_CAPTURE+'/portal-admin-desktop.png'})
  await page.getByRole('button',{name:'高级设置',exact:true}).click()
  for (const label of ['解析上游','客户端','证书','监听服务']){
    await page.getByRole('button',{name:label,exact:true}).click()
    const [panel,tabs] = await page.evaluate(()=>['main .panel','main .section-nav'].map(s=>document.querySelector(s).getBoundingClientRect().right))
    assert(Math.abs(panel-tabs)<1,label+' panel width')
  }
  await page.getByRole('button',{name:'用户管理',exact:true}).click()
  await page.getByLabel('账号密码登录与注册').uncheck()
  await page.getByLabel('允许登录的邮箱后缀').waitFor()
  await page.getByRole('button',{name:'添加 OAuth 2.0',exact:true}).waitFor()
  await page.getByRole('button',{name:'添加 OpenID Connect',exact:true}).waitFor()
  await page.getByLabel('注册策略').selectOption('approval')
  await page.getByRole('button', { name: '保存并应用' }).click()
  await page.getByRole('status').filter({hasText:'已应用'}).waitFor()
  const filterByUser = page.getByLabel('用户筛选', { exact: true })
  const aliceOption = await filterByUser.getByRole('option',{name:/^alice · #/}).getAttribute('value')
  await filterByUser.selectOption(aliceOption)
  await page.getByText('portal.test', { exact: true }).first().waitFor()
  const rejected = await page.evaluate(
    (secret) =>
      new Promise((resolve) => {
        const ws = new WebSocket('ws://' + location.host + '/api/v1/ws')
        ws.onopen = () => ws.send(JSON.stringify({ type: 'auth', token: secret }))
        ws.onclose = (e) => resolve(e.code)
        ws.onmessage = (e) => {
          if (JSON.parse(e.data).type === 'ready') {
            ws.close()
            resolve(0)
          }
        }
      }),
    cookie.value,
  )
  assert.equal(rejected, 1008)
  await page.getByRole('button', { name: '管理员', exact: true }).click()
  const newPassword = 'test-new-console-password'
  await page.getByLabel('当前密码', { exact: true }).fill('incorrect-password')
  await page.getByLabel('新密码', { exact: true }).fill(newPassword)
  await page.getByLabel('确认新密码', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: '当前密码不正确' }).waitFor()
  await page.getByLabel('当前密码', { exact: true }).fill(process.env.RDNS_TEST_ADMIN_PASSWORD)
  await page.getByRole('button', { name: '修改密码', exact: true }).click()
  await page.getByText('密码已修改，请使用新密码登录。').waitFor()
  const request = context.request
  assert.equal((await request.get(admin+'/api/v1/me',{headers:{Authorization:'Bearer '+token}})).status(),401)
  assert.equal((await request.post(admin+'/api/v1/login',{data:{username:'admin',password:process.env.RDNS_TEST_ADMIN_PASSWORD}})).status(),401)
  await page.getByLabel('用户名',{exact:true}).fill('admin')
  await page.getByLabel('密码',{exact:true}).fill(newPassword)
  await page.getByRole('button',{name:/登录控制台/}).click()
  await page.getByRole('button',{name:'退出',exact:true}).waitFor()
} finally {
  await browser.close()
}
